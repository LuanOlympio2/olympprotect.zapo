function styleText(text) {
    const styles = [];
    for (const styleName of Object.keys(styleMappings)) {
        const mapping = styleMappings[styleName];
        let transformed = '';
        for (const char of text) {
            transformed += mapping[char] || char;
        }
        styles.push(transformed);
    }
    return styles;
}
module.exports = {
    name: 'gerarnick',
    description: 'Gera estilos de nick usando variações de fontes Unicode',
    usage: '!gerarnick <texto>',
    aliases: ['gerarnick'],
    run: async (conn, msg, config, args, sender, senderName) => {
        if (args.length === 0) {
            return conn.sendMessage(msg.key.remoteJid, { text: 'Uso: !gerarnick <texto>' }, { quoted: msg });
        }
        const text = args.join(' ');
        try {
            const styles = styleText(text);
            const response = styles.join('\n');
            await conn.sendMessage(msg.key.remoteJid, { text: response }, { quoted: msg });
        } catch (e) {
            await conn.sendMessage(msg.key.remoteJid, { text: `Erro ao gerar estilos: ${e.message}` }, { quoted: msg });
        }
    }
};
